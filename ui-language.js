function createBarevLanguage(root, onChange = () => {}) {
  const key = "barev.language";
  const supported = ["en", "ru", "hy"];
  let language = "en";
  try { language = localStorage.getItem(key) || "en"; } catch {}
  const text = (english, values = {}) => {
    const translated = barevCopy[english]?.[language === "ru" ? 0 : language === "hy" ? 1 : -1] || english;
    return translated.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
  };
  function refresh() {
    document.documentElement.lang = language;
    for (const el of root.querySelectorAll("[data-copy]")) el.textContent = text(el.dataset.copy);
    for (const el of root.querySelectorAll("[data-copy-label]")) el.setAttribute("aria-label", text(el.dataset.copyLabel));
    for (const el of root.querySelectorAll("[data-copy-placeholder]")) el.placeholder = text(el.dataset.copyPlaceholder);
    for (const button of root.querySelectorAll("[data-lang]")) {
      button.setAttribute("aria-pressed", String(button.dataset.lang === language));
    }
  }
  function update(next, save) {
    if (!supported.includes(next)) return;
    language = next;
    if (save) try { localStorage.setItem(key, language); } catch {}
    refresh();
    onChange(text);
  }
  for (const button of root.querySelectorAll("[data-lang]")) {
    button.addEventListener("click", () => update(button.dataset.lang, true));
  }
  window.addEventListener("storage", event => {
    if (event.key === key && event.newValue !== language) update(event.newValue || "en", false);
  });
  if (!supported.includes(language)) language = "en";
  refresh();
  return { text, refresh };
}
